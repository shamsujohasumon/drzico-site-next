// Runs before every build (npm run build -> prebuild).
// 1. Image optimizer: for every photo in public/assets/img (outside _opt) it makes WebP copies at
//    240/480/720/960/1600 px wide in public/assets/img/_opt (same folders) and records them in
//    content/image-manifest.json. A photo is only re-encoded when it is new or its content changed.
//    You keep adding normal JPG/PNG photos; never edit _opt by hand.
// 2. Writes public/assets/js/conditions.js (search data for the condition finder).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const IMG = path.join(ROOT, "public", "assets", "img");
const OPT = "_opt";
const WIDTHS = [240, 480, 720, 960, 1600];
const QUALITY = 78;
// icons and the share image are used as they are
const SKIP = /^(favicon-|icon-|apple-touch-icon|og-image)/;
const MANIFEST = path.join(ROOT, "content", "image-manifest.json");

const old = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, "utf8")) : {};
const manifest = {};

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === OPT || e.name.startsWith(".")) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (/\.(jpe?g|png|webp)$/i.test(e.name) && !SKIP.test(e.name)) out.push(p);
  }
  return out;
}

let made = 0;
for (const src of walk(IMG).sort()) {
  const rel = path.relative(IMG, src).split(path.sep).join("/");
  const buf = fs.readFileSync(src);
  const hash = crypto.createHash("sha1").update(buf).digest("hex");
  const meta = await sharp(buf).metadata();
  const ow = meta.width, oh = meta.height;
  const widths = [...new Set([...WIDTHS.filter((w) => w < ow), Math.min(ow, WIDTHS[WIDTHS.length - 1])])].sort((a, b) => a - b);
  const base = rel.replace(/\.[^.]+$/, "");
  const variants = [];
  for (const w of widths) {
    const name = `${OPT}/${base}-${w}.webp`;
    const dst = path.join(IMG, name);
    // fresh = variant exists and the original did not change (first run: trust existing variants)
    const fresh = fs.existsSync(dst) && (!old[rel] || old[rel].hash === hash);
    if (!fresh) {
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      await sharp(buf).resize({ width: w, height: Math.round((oh * w) / ow) }).webp({ quality: QUALITY, effort: 5 }).toFile(dst);
      made++;
    }
    variants.push([name, w]);
  }
  manifest[rel] = { w: ow, h: oh, hash, variants };
}
fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1) + "\n");

// condition finder data
const site = JSON.parse(fs.readFileSync(path.join(ROOT, "content", "site-data.json"), "utf8"));
const conditions = site.CONDITIONS.map((c) => ({ ...c, url: c.url.replace(/\.html(?=#|$)/, "") }));
fs.writeFileSync(path.join(ROOT, "public", "assets", "js", "conditions.js"),
  "/* generated by scripts/prepare.mjs */\nwindow.DZ_CONDITIONS = " + JSON.stringify(conditions, null, 1) + ";\n");

console.log(`images: ${Object.keys(manifest).length} originals, ${made} new optimized copies`);
